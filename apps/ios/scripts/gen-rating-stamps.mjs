// Inlines web's rating stamp SVGs into src/ratingStamps.ts so SvgXml can draw them without a Metro SVG transformer.
// Run from apps/ios: node scripts/gen-rating-stamps.mjs
import { readFileSync, writeFileSync } from "node:fs";

const NAMES = ["one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"];
const pub = new URL("../../web/public/", import.meta.url);
const read = (path) => JSON.stringify(readFileSync(new URL(path, pub), "utf8").trim());

const on = NAMES.map((n) => read(`rating_stamps/${n}-ratingStamp.svg`));
const off = NAMES.map((n) => read(`empty_rating_stamps/${n}Empty-ratingStamp.svg`));

writeFileSync(
  new URL("../src/ratingStamps.ts", import.meta.url),
  `// Generated by scripts/gen-rating-stamps.mjs from apps/web/public. Do not edit.
/** Filled stamp SVG per rating; index 0 is rating 1. */
export const STAMPS_ON: readonly string[] = [
${on.map((s) => `  ${s},`).join("\n")}
];
/** Empty stamp SVG per rating; index 0 is rating 1. */
export const STAMPS_OFF: readonly string[] = [
${off.map((s) => `  ${s},`).join("\n")}
];
`,
);
